import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

// Compile at development time: the browser/portable reader needs neither Node
// filesystem access nor eval/Function (including under a strict host CSP).
const root = new URL("../", import.meta.url);
const require = createRequire(import.meta.url);
const schemas = await Promise.all(["run-record", "cloud-focus"].map(async (name) =>
  JSON.parse(await readFile(new URL(`protocol/v2/${name}.schema.json`, root), "utf8"))));
const ajv = new Ajv2020({ allErrors: true, strict: true, allowUnionTypes: true, code: { source: true, esm: true } });
for (const schema of schemas) ajv.addSchema(schema);
const exports = { structural: schemas[0].$id };
const entries = [];
for (const schema of schemas) for (const name of Object.keys(schema.$defs)) {
  const uri = `${schema.$id}#/$defs/${name}`;
  const key = `definitionValidator${entries.length}`;
  exports[key] = uri;
  entries.push([uri, key]);
}
let code = standaloneCode(ajv, exports);
code = code.replace(/const (\w+) = require\("(ajv\/dist\/runtime\/[^"\n]+)"\)\.default;/g, (_, name, path) => {
  // These pinned helpers have no free module references. Keep raw source usable
  // by the repository's unbundled browser tests as well as packed consumers.
  if (!["ajv/dist/runtime/ucs2length", "ajv/dist/runtime/equal"].includes(path)) throw new Error(`Unreviewed standalone helper: ${path}`);
  return `const ${name} = ${require(`${path}.js`).default.toString()};`;
});
if (/\brequire\s*\(/.test(code)) throw new Error("Unexpected runtime dependency in standalone validator");
const output = `// Code generated by scripts/generate-protocol-v2-validator.js. DO NOT EDIT.\n// Ajv and fast-deep-equal helpers: MIT; see THIRD_PARTY_NOTICES.md.\n${code}\n`
  + `export const contentValidators = new Map([${entries.map(([uri, key]) => `[${JSON.stringify(uri)},${key}]`).join(",")}]);\n`
  + `export const runRecordSchema = ${JSON.stringify(schemas[0])};\nexport const cloudFocusSchema = ${JSON.stringify(schemas[1])};\n`;
const target = new URL("src/protocol-v2-generated.js", root);
if (process.argv.includes("--check")) {
  if (await readFile(target, "utf8") !== output) throw new Error("Generated v2 validator differs; run npm run generate:protocol-v2-validator");
  console.log("Checked browser v2 validator");
} else {
  await writeFile(target, output);
  console.log("Generated browser v2 validator");
}
